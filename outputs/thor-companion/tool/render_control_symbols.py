"""Generate client paths and Web Ops SVG symbols from one icon source."""
from pathlib import Path
import json,re
client=Path(__file__).resolve().parents[1]
web=client.parent/'thor-monitor-prototype/assets/web-ops'
symbols=json.loads((web/'control-symbols.json').read_text())
rows=['// Generated by tool/render_control_symbols.py.','const controlSymbolPaths = <String, List<String>>{']
for key,icon in symbols.items():
 for path in icon['paths']:
  assert not re.sub(r'[MLCZ0-9.\s-]','',path),path
 rows.append('  '+json.dumps(key)+': ['+', '.join(json.dumps(p) for p in icon['paths'])+'],')
rows.append('};\n')
(client/'lib/control_symbol_paths.dart').write_text('\n'.join(rows))
html=(web/'index.html').read_text()
for icon in symbols.values():
 name=icon['symbol'];svg=f'<symbol id="ui-{name}" viewBox="0 0 24 24">'+''.join(f'<path d="{p}"/>' for p in icon['paths'])+'</symbol>'
 html,count=re.subn(r'<symbol id="ui-'+name+r'"[^>]*>.*?</symbol>',lambda _:svg,html)
 assert count==1,(name,count)
(web/'index.html').write_text(html)
